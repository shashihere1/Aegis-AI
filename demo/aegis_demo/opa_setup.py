"""Run a local Open Policy Agent server for Aegis (policy_engine=opa).

    python -m aegis_demo.opa_setup start      # serves config/policies on http://127.0.0.1:8181
    python -m aegis_demo.opa_setup status | stop | env | check | test

OPA ships as a single binary. Point AEGIS_OPA_BINARY at it, put `opa` on PATH, or save it as
%USERPROFILE%\\Downloads\\opa\\opa_windows_amd64.exe (on Infosys laptops fetch it through the approved Artifactory
route; direct GitHub downloads are blocked). The server loads only the runtime Rego (test files are excluded) plus
data.json; Aegis then refuses to use it unless its loaded policy matches the approved Rego byte for byte.
"""

import argparse
import os
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

from aegis.common.settings import REPO_ROOT

HOME = REPO_ROOT / ".local" / "opa"
POLICY_DIR = REPO_ROOT / "config" / "policies"
PORT = 8181
URL = f"http://127.0.0.1:{PORT}"
DEFAULT_BINARY = Path.home() / "Downloads" / "opa" / ("opa_windows_amd64.exe" if os.name == "nt" else "opa")


def find_binary() -> str | None:
    """AEGIS_OPA_BINARY, then `opa` on PATH, then the usual download location."""
    configured = os.environ.get("AEGIS_OPA_BINARY", "")
    if configured and Path(configured).is_file():
        return configured
    on_path = shutil.which("opa")
    if on_path:
        return on_path
    return str(DEFAULT_BINARY) if DEFAULT_BINARY.is_file() else None


def require_binary() -> str:
    binary = find_binary()
    if binary is None:
        raise SystemExit(
            "No OPA binary found. Set AEGIS_OPA_BINARY, put `opa` on PATH, or save it as "
            f"{DEFAULT_BINARY}.\nThe file is the OPA release asset opa_windows_amd64.exe (Linux: opa_linux_amd64)."
        )
    return binary


def server_command(binary: str, port: int = PORT, policy_dir: Path = POLICY_DIR) -> list[str]:
    return [
        binary,
        "run",
        "--server",
        f"--addr=127.0.0.1:{port}",
        "--ignore=*_test.rego",  # unit tests are for `opa test`, not for the decision server
        "--log-level=error",
        str(policy_dir),
    ]


def healthy(url: str = URL, timeout: float = 0) -> bool:
    deadline = time.monotonic() + timeout
    while True:
        try:
            with urllib.request.urlopen(f"{url}/health", timeout=2) as reply:
                if reply.status == 200:
                    return True
        except (urllib.error.URLError, OSError):
            pass
        if time.monotonic() >= deadline:
            return False
        time.sleep(0.5)


def pid_file() -> Path:
    return HOME / "opa.pid"


def start() -> None:
    if healthy():
        print(f"OPA is already running at {URL}")
        return
    binary = require_binary()
    HOME.mkdir(parents=True, exist_ok=True)
    log = (HOME / "opa.log").open("ab")
    flags = (subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW) if os.name == "nt" else 0
    process = subprocess.Popen(
        server_command(binary), stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, creationflags=flags
    )
    pid_file().write_text(str(process.pid))
    if not healthy(timeout=20):
        tail = "\n".join((HOME / "opa.log").read_text("utf-8", "replace").splitlines()[-15:])
        raise SystemExit(f"OPA did not become healthy. Last log lines:\n{tail}")
    print(f"OPA is serving {POLICY_DIR} at {URL}")
    print(f"Point Aegis at it (PowerShell):  . .\\.local\\opa\\aegis-opa-env.ps1   (written to {write_env()})")


def stop() -> None:
    if not pid_file().exists():
        print("No OPA started by this tool.")
        return
    pid = pid_file().read_text().strip()
    command = ["taskkill", "/PID", pid, "/T", "/F"] if os.name == "nt" else ["kill", pid]
    subprocess.run(command, capture_output=True)
    pid_file().unlink(missing_ok=True)
    print("OPA stopped.")


def write_env() -> Path:
    HOME.mkdir(parents=True, exist_ok=True)
    path = HOME / "aegis-opa-env.ps1"
    path.write_text(
        "# Generated by aegis_demo.opa_setup - dot-source it:  . .\\.local\\opa\\aegis-opa-env.ps1\n"
        "$env:AEGIS_POLICY_ENGINE = 'opa'\n"
        f"$env:AEGIS_OPA_URL = '{URL}'\n",
        encoding="utf-8",
    )
    return path


def run_tool(*args: str) -> int:
    """`opa check` / `opa test` on the policy directory, exactly as CI runs them."""
    return subprocess.run([require_binary(), *args, str(POLICY_DIR)]).returncode


def main() -> int:
    parser = argparse.ArgumentParser(description="Local OPA server for Aegis")
    parser.add_argument("action", choices=["start", "stop", "status", "env", "check", "test"])
    action = parser.parse_args().action
    if action == "start":
        start()
    elif action == "stop":
        stop()
    elif action == "status":
        print(("healthy" if healthy() else "not running"), "-", URL, "| binary:", find_binary() or "not found")
    elif action == "env":
        print(write_env().read_text("utf-8"))
    elif action == "check":
        return run_tool("check")
    else:
        return run_tool("test", "-v")
    return 0


if __name__ == "__main__":
    sys.exit(main())
